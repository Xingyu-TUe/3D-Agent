/**
 * build-wechat.js
 * 把模块化源码打包成微信小游戏可运行的【单文件】game.js（IIFE，无 import/export）。
 *
 * 用法：npm run build:wechat
 *
 * 产出：
 *   game.js                 — 微信入口（单文件打包）
 *   dist/wechat/            — 可直接导入开发者工具的干净项目
 *   dist/HellRift.zip       — 上述目录的压缩包
 */

import * as esbuild from 'esbuild';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { execFileSync } from 'child_process';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

async function main() {
  const outfile = path.join(root, 'game.js');

  await esbuild.build({
    entryPoints: [path.join(root, 'src', 'wechat-entry.js')],
    bundle: true,
    outfile,
    format: 'iife',
    platform: 'neutral',
    target: ['es2017'],
    minify: false,
    sourcemap: false,
    logLevel: 'info',
    banner: {
      js: '/* HellRift WeChat bundle — generated by npm run build:wechat. DO NOT EDIT. */\n',
    },
  });

  execFileSync(process.execPath, ['--check', outfile], { stdio: 'inherit' });

  // 组装干净的微信导入目录（绝不包含 src/ scripts/ index.html 等）
  const wechatDir = path.join(root, 'dist', 'wechat');
  fs.rmSync(wechatDir, { recursive: true, force: true });
  fs.mkdirSync(wechatDir, { recursive: true });

  fs.copyFileSync(outfile, path.join(wechatDir, 'game.js'));
  fs.copyFileSync(path.join(root, 'game.json'), path.join(wechatDir, 'game.json'));

  // 贴图目录（运行时按 Assets/ 相对路径加载，不内联进 game.js）
  const assetsSrc = path.join(root, 'src', 'Assets');
  const assetsDst = path.join(wechatDir, 'Assets');
  if (fs.existsSync(assetsSrc)) {
    fs.cpSync(assetsSrc, assetsDst, { recursive: true });
  } else {
    console.warn('[HellRift] 缺少 src/Assets，请先 npm run generate:assets');
  }

  const projectConfig = {
    description: '地狱裂隙 Hell Rift - 微信小游戏（单文件打包版）',
    setting: {
      es6: true,
      enhance: true,
      postcss: false,
      minified: false,
      newFeature: true,
    },
    compileType: 'game',
    appid: 'touristappid',
    projectname: 'HellRift',
    miniprogramRoot: './',
    srcMiniprogramRoot: './',
  };
  fs.writeFileSync(
    path.join(wechatDir, 'project.config.json'),
    JSON.stringify(projectConfig, null, 2),
  );

  fs.writeFileSync(
    path.join(wechatDir, '导入说明.txt'),
    [
      '地狱裂隙 Hell Rift — 微信使用说明',
      '',
      '【第一次导入】',
      '1. 解压 HellRift.zip，得到 HellRift 文件夹',
      '2. 确认该文件夹里能直接看到：game.js、game.json、project.config.json、Assets/',
      '   （不要选到上一级，也不要选到空文件夹）',
      '3. 微信开发者工具 → 新建小游戏 → 目录选这个 HellRift 文件夹',
      '4. AppID 选「测试号」→ 创建 → 编译',
      '',
      '【报错「game.js 未找到」怎么修】',
      '说明当前打开的目录里没有 game.js。任选其一：',
      'A. 双击本目录「检查项目.bat」确认缺什么，再双击「更新游戏.bat」自动补全',
      'B. 浏览器打开下面链接，另存为覆盖本目录 game.js，再点「编译」：',
      '   https://cdn.jsdelivr.net/gh/Xingyu-TUe/3D-Agent@cursor/hell-rift-wechat-game-b0ee/game.js',
      'C. 重新解压 zip，用开发者工具「导入项目」指向解压后的 HellRift',
      '',
      '【贴图 Assets/】',
      '角色/怪物/UI 贴图在 Assets/ 目录，必须与 game.js 同级。',
      '只更新 game.js 不够时，请重新下载 HellRift.zip 覆盖整个文件夹。',
      '',
      '【以后更新 —— 不用重新导入】',
      '双击「更新游戏.bat」→ 回开发者工具点「编译」即可。',
      '若贴图也有更新，请重新解压 zip 覆盖 Assets/。',
      '',
      '本包为单文件打包版 + Assets 贴图。鼠标按住模拟器左半屏 = 摇杆。',
      '',
    ].join('\n'),
  );

  // Windows 辅助脚本
  const updateDir = path.join(root, 'scripts', 'wechat-update');
  for (const name of ['更新游戏.bat', '检查项目.bat']) {
    const src = path.join(updateDir, name);
    if (fs.existsSync(src)) fs.copyFileSync(src, path.join(wechatDir, name));
  }

  // 打 zip（临时用 HellRift 目录名）
  const dist = path.join(root, 'dist');
  const hellDir = path.join(dist, 'HellRift');
  fs.rmSync(hellDir, { recursive: true, force: true });
  fs.cpSync(wechatDir, hellDir, { recursive: true });

  const zipPath = path.join(dist, 'HellRift.zip');
  fs.rmSync(zipPath, { force: true });
  execFileSync('zip', ['-rq', zipPath, 'HellRift'], { cwd: dist });
  fs.rmSync(hellDir, { recursive: true, force: true });

  const size = fs.statSync(zipPath).size;
  const gameSize = fs.statSync(outfile).size;
  console.log(`[HellRift] game.js 打包完成 (${Math.round(gameSize / 1024)} KB)`);
  console.log(`[HellRift] 微信包: dist/HellRift.zip (${Math.round(size / 1024)} KB)`);
  console.log('[HellRift] 导入目录: dist/wechat/');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
